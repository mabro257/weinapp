-- Erweiterungen für Suche mit Tippfehler-Toleranz und ohne Akzente
create extension if not exists pg_trgm with schema extensions;
create extension if not exists unaccent with schema extensions;

-- Text normalisieren: Kleinbuchstaben, ohne Akzente ("Côtes" -> "cotes")
create or replace function public.norm(t text) returns text
language sql immutable parallel safe set search_path = ''
as $$ select lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t, ''))) $$;

-- ---------------------------------------------------------------------
-- Tabellen
-- ---------------------------------------------------------------------

-- Nutzerprofil, wird bei der ersten Anmeldung automatisch angelegt
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Neu',
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

-- Rebsorten mit Glossar-Texten
create table public.grapes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  synonyms text[] not null default '{}',
  color text not null check (color in ('rot', 'weiss')),
  short text,
  aromas text[] not null default '{}',
  regions text,
  body smallint check (body between 1 and 5),
  acidity smallint check (acidity between 1 and 5),
  tannin smallint check (tannin between 1 and 5),
  food text
);

-- Weinkatalog (jahrgangsunabhängig)
create table public.wines (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) > 0),
  winery text,
  country text,
  region text,
  type text check (type in ('rot', 'weiss', 'rose', 'schaum')),
  price_class smallint check (price_class between 1 and 4),
  body smallint check (body between 1 and 5),
  acidity smallint check (acidity between 1 and 5),
  label_path text,
  source text not null default 'manuell' check (source in ('import', 'manuell', 'demo')),
  external_id text,
  status text not null default 'offen' check (status in ('offen', 'geprueft')),
  merged_into bigint references public.wines (id),
  search_text text not null default '',
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create index wines_search_trgm on public.wines using gin (search_text extensions.gin_trgm_ops);
create unique index wines_external_id on public.wines (source, external_id) where external_id is not null;

-- Rebsorten je Wein, position 1 = Hauptrebsorte
create table public.wine_grapes (
  wine_id bigint not null references public.wines (id) on delete cascade,
  grape_id bigint not null references public.grapes (id),
  position smallint not null default 1,
  primary key (wine_id, grape_id)
);
create index wine_grapes_grape on public.wine_grapes (grape_id);

-- Bewertungen, mehrere pro Nutzer und Wein erlaubt
create table public.ratings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  wine_id bigint not null references public.wines (id) on delete cascade,
  score smallint not null check (score between 1 and 100),
  vintage smallint check (vintage between 1900 and 2100),
  tasted_on date not null default current_date,
  body smallint check (body between 1 and 5),
  acidity smallint check (acidity between 1 and 5),
  tannin smallint check (tannin between 1 and 5),
  note text,
  tags text[] not null default '{}',
  created_at timestamptz not null default now()
);
create index ratings_user on public.ratings (user_id);
create index ratings_wine on public.ratings (wine_id);

-- ---------------------------------------------------------------------
-- Hilfsfunktionen und Trigger
-- ---------------------------------------------------------------------

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select coalesce((select p.is_admin from public.profiles p where p.id = auth.uid()), false) $$;

-- Profil bei Registrierung anlegen (Anzeigename = Teil der E-Mail vor dem @)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name) values (new.id, split_part(new.email, '@', 1));
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Suchtext pflegen: Name, Weingut, Region, Land und Rebsorten inkl. Synonymen
create or replace function public.wines_search_trigger() returns trigger
language plpgsql set search_path = ''
as $$
begin
  new.search_text := public.norm(concat_ws(' ', new.name, new.winery, new.region, new.country,
    (select string_agg(g.name || ' ' || array_to_string(g.synonyms, ' '), ' ')
       from public.wine_grapes wg join public.grapes g on g.id = wg.grape_id
      where wg.wine_id = new.id)));
  return new;
end $$;
create trigger wines_search before insert or update of name, winery, region, country on public.wines
  for each row execute function public.wines_search_trigger();

create or replace function public.wine_grapes_touch() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  update public.wines set name = name where id = coalesce(new.wine_id, old.wine_id);
  return null;
end $$;
create trigger wine_grapes_touch after insert or delete on public.wine_grapes
  for each row execute function public.wine_grapes_touch();

-- ---------------------------------------------------------------------
-- Zugriffsregeln (Row Level Security)
-- ---------------------------------------------------------------------

alter table public.profiles enable row level security;
alter table public.grapes enable row level security;
alter table public.wines enable row level security;
alter table public.wine_grapes enable row level security;
alter table public.ratings enable row level security;

-- Profile: alle Angemeldeten sehen Anzeigenamen, ändern nur den eigenen Namen
create policy "Profile lesen" on public.profiles for select to authenticated using (true);
create policy "Eigenes Profil ändern" on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());
revoke update on public.profiles from anon, authenticated;
grant update (display_name) on public.profiles to authenticated;

-- Rebsorten: lesen alle, pflegen nur Admin
create policy "Rebsorten lesen" on public.grapes for select to authenticated using (true);
create policy "Rebsorten pflegen" on public.grapes for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- Weine: lesen alle, anlegen alle, ändern der Admin oder der Ersteller (solange ungeprüft)
create policy "Weine lesen" on public.wines for select to authenticated using (true);
create policy "Weine anlegen" on public.wines for insert to authenticated
  with check (created_by = auth.uid() and status = 'offen');
create policy "Weine ändern" on public.wines for update to authenticated
  using (public.is_admin() or (created_by = auth.uid() and status = 'offen'))
  with check (public.is_admin() or (created_by = auth.uid() and status = 'offen'));
create policy "Weine löschen" on public.wines for delete to authenticated using (public.is_admin());

create policy "Weinrebsorten lesen" on public.wine_grapes for select to authenticated using (true);
create policy "Weinrebsorten anlegen" on public.wine_grapes for insert to authenticated
  with check (public.is_admin() or exists (
    select 1 from public.wines w where w.id = wine_id and w.created_by = auth.uid() and w.status = 'offen'));
create policy "Weinrebsorten löschen" on public.wine_grapes for delete to authenticated
  using (public.is_admin() or exists (
    select 1 from public.wines w where w.id = wine_id and w.created_by = auth.uid() and w.status = 'offen'));

-- Bewertungen: jeder sieht und ändert nur die eigenen
create policy "Eigene Bewertungen" on public.ratings for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

