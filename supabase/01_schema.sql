-- Katalogsuche: alle Suchwörter müssen passen, Tippfehler werden toleriert
create or replace function public.search_wines(q text, lim int default 20)
returns table (id bigint, name text, winery text, region text, main_grape text, my_avg numeric)
language plpgsql set search_path = ''
as $$
declare
  toks text[] := array(select t from unnest(regexp_split_to_array(public.norm(q), '\s+')) t where t <> '');
begin
  if coalesce(array_length(toks, 1), 0) = 0 then
    return;
  end if;
  perform set_config('pg_trgm.word_similarity_threshold', '0.3', true);
  return query
  select w.id, w.name, w.winery, w.region,
    (select g.name from public.wine_grapes wg join public.grapes g on g.id = wg.grape_id
      where wg.wine_id = w.id order by wg.position limit 1),
    (select round(avg(r.score)) from public.ratings r where r.wine_id = w.id and r.user_id = auth.uid())
  from public.wines w
  where w.merged_into is null
    and not exists (
      select 1 from unnest(toks) t
      where not (strpos(w.search_text, t) > 0 or t operator(extensions.<%) w.search_text))
  -- Treffer im Weinnamen zählen mehr als in Weingut/Region, exakte mehr als ähnliche
  order by (select sum(case
                         when strpos(public.norm(w.name), t) > 0 then 2
                         when strpos(w.search_text, t) > 0 then 1
                         else 2 * extensions.word_similarity(t, public.norm(w.name))
                       end) from unnest(toks) t) desc,
           length(w.name), w.name
  limit lim;
end $$;

-- Ähnliche Weine beim Neuanlegen (gegen Dubletten)
create or replace function public.similar_wines(p_name text, p_winery text)
returns table (id bigint, name text, winery text, region text, main_grape text, my_avg numeric)
language sql stable set search_path = ''
as $$
  select w.id, w.name, w.winery, w.region,
    (select g.name from public.wine_grapes wg join public.grapes g on g.id = wg.grape_id
      where wg.wine_id = w.id order by wg.position limit 1),
    null::numeric
  from public.wines w
  where w.merged_into is null
    and extensions.similarity(public.norm(concat_ws(' ', w.name, w.winery)),
                              public.norm(concat_ws(' ', p_name, p_winery))) > 0.35
  order by extensions.similarity(public.norm(concat_ws(' ', w.name, w.winery)),
                                 public.norm(concat_ws(' ', p_name, p_winery))) desc
  limit 3
$$;

-- Community-Durchschnitt eines Weins: gesamt (is_total) und je Jahrgang.
-- Läuft mit erweiterten Rechten, gibt aber nur Durchschnitte heraus, keine Einzelbewertungen.
create or replace function public.wine_community(p_wine bigint)
returns table (is_total boolean, vintage smallint, avg_score numeric, n bigint, raters bigint,
               avg_body numeric, avg_acidity numeric, avg_tannin numeric)
language sql stable security definer set search_path = ''
as $$
  select grouping(r.vintage) = 1, r.vintage, avg(r.score), count(*), count(distinct r.user_id),
         avg(r.body), avg(r.acidity), avg(r.tannin)
  from public.ratings r
  where r.wine_id = p_wine and auth.uid() is not null
  group by grouping sets ((), (r.vintage))
$$;

-- Durchschnitt aller Nutzer je Hauptrebsorte (für den Decider)
create or replace function public.grape_community()
returns table (grape_id bigint, avg_score numeric, n bigint)
language sql stable security definer set search_path = ''
as $$
  select wg.grape_id, avg(r.score), count(*)
  from public.ratings r
  join public.wine_grapes wg on wg.wine_id = r.wine_id and wg.position = 1
  where auth.uid() is not null
  group by wg.grape_id
$$;

-- Etikettfoto setzen, aber nur wenn der Wein noch keins hat
create or replace function public.set_wine_label(p_wine bigint, p_path text)
returns void
language sql security definer set search_path = ''
as $$
  update public.wines set label_path = p_path
  where id = p_wine and label_path is null and auth.uid() is not null
$$;

-- Admin: doppelten Wein in einen anderen überführen (Bewertungen ziehen mit um)
create or replace function public.merge_wines(p_from bigint, p_into bigint)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Nur für Admins';
  end if;
  update public.ratings set wine_id = p_into where wine_id = p_from;
  update public.wines set merged_into = p_into where id = p_from;
end $$;

