-- ---------------------------------------------------------------------
-- 1. Gruppen und Mitglieder
-- ---------------------------------------------------------------------
create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 60),
  invite_code text not null unique default upper(substr(md5(gen_random_uuid()::text), 1, 8)),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id bigint not null references public.groups (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role text not null default 'member' check (role in ('admin', 'member')),
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);
create index if not exists group_members_user on public.group_members (user_id);

-- Hilfsfunktionen (mit erweiterten Rechten, damit sich die Zugriffsregeln nicht selbst blockieren)
create or replace function public.my_group_ids() returns setof bigint
language sql stable security definer set search_path = ''
as $$ select gm.group_id from public.group_members gm where gm.user_id = auth.uid() $$;

create or replace function public.my_friend_ids() returns setof uuid
language sql stable security definer set search_path = ''
as $$
  select distinct gm2.user_id
  from public.group_members gm1
  join public.group_members gm2 on gm2.group_id = gm1.group_id
  where gm1.user_id = auth.uid() and gm2.user_id <> auth.uid()
$$;

create or replace function public.is_group_admin(p_group bigint) returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.group_members gm where gm.group_id = p_group and gm.user_id = auth.uid() and gm.role = 'admin') $$;

alter table public.groups enable row level security;
alter table public.group_members enable row level security;

drop policy if exists "Gruppen lesen" on public.groups;
create policy "Gruppen lesen" on public.groups for select to authenticated
  using (id in (select public.my_group_ids()));
drop policy if exists "Gruppe umbenennen" on public.groups;
create policy "Gruppe umbenennen" on public.groups for update to authenticated
  using (public.is_group_admin(id)) with check (public.is_group_admin(id));
drop policy if exists "Gruppe löschen" on public.groups;
create policy "Gruppe löschen" on public.groups for delete to authenticated
  using (public.is_group_admin(id));

drop policy if exists "Mitglieder lesen" on public.group_members;
create policy "Mitglieder lesen" on public.group_members for select to authenticated
  using (group_id in (select public.my_group_ids()));
drop policy if exists "Gruppe verlassen" on public.group_members;
create policy "Gruppe verlassen" on public.group_members for delete to authenticated
  using (user_id = auth.uid() or public.is_group_admin(group_id));

grant select, update, delete on public.groups to authenticated;
grant select, delete on public.group_members to authenticated;

-- Gruppe anlegen (Ersteller wird Admin)
create or replace function public.create_group(p_name text)
returns table (id bigint, invite_code text)
language plpgsql security definer set search_path = ''
as $$
declare
  g public.groups;
begin
  if auth.uid() is null then raise exception 'Nicht angemeldet'; end if;
  insert into public.groups (name, created_by) values (trim(p_name), auth.uid()) returning * into g;
  insert into public.group_members (group_id, user_id, role) values (g.id, auth.uid(), 'admin');
  return query select g.id, g.invite_code;
end $$;

-- Gruppe per Einladungscode beitreten
create or replace function public.join_group(p_code text)
returns bigint
language plpgsql security definer set search_path = ''
as $$
declare
  gid bigint;
begin
  if auth.uid() is null then raise exception 'Nicht angemeldet'; end if;
  select g.id into gid from public.groups g where g.invite_code = upper(trim(p_code));
  if gid is null then raise exception 'Einladungscode ungültig'; end if;
  insert into public.group_members (group_id, user_id) values (gid, auth.uid()) on conflict do nothing;
  return gid;
end $$;

-- ---------------------------------------------------------------------
-- 2. Weinabende
-- ---------------------------------------------------------------------
create table if not exists public.tastings (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups (id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 80),
  event_date date not null default current_date,
  host uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  status text not null default 'offen' check (status in ('offen', 'aufgeloest')),
  created_at timestamptz not null default now()
);
create index if not exists tastings_group on public.tastings (group_id);

create table if not exists public.tasting_wines (
  tasting_id bigint not null references public.tastings (id) on delete cascade,
  wine_id bigint not null references public.wines (id) on delete cascade,
  position smallint not null default 1,
  primary key (tasting_id, wine_id)
);

create or replace function public.tasting_is_open(p_tasting bigint) returns boolean
language sql stable security definer set search_path = ''
as $$ select coalesce((select t.status = 'offen' from public.tastings t where t.id = p_tasting), false) $$;

alter table public.tastings enable row level security;
alter table public.tasting_wines enable row level security;

drop policy if exists "Weinabende lesen" on public.tastings;
create policy "Weinabende lesen" on public.tastings for select to authenticated
  using (group_id in (select public.my_group_ids()));
drop policy if exists "Weinabend anlegen" on public.tastings;
create policy "Weinabend anlegen" on public.tastings for insert to authenticated
  with check (host = auth.uid() and group_id in (select public.my_group_ids()));
drop policy if exists "Weinabend ändern" on public.tastings;
create policy "Weinabend ändern" on public.tastings for update to authenticated
  using (host = auth.uid()) with check (host = auth.uid());
drop policy if exists "Weinabend löschen" on public.tastings;
create policy "Weinabend löschen" on public.tastings for delete to authenticated
  using (host = auth.uid());

drop policy if exists "Weine des Abends lesen" on public.tasting_wines;
create policy "Weine des Abends lesen" on public.tasting_wines for select to authenticated
  using (tasting_id in (select t.id from public.tastings t));
drop policy if exists "Weine des Abends pflegen" on public.tasting_wines;
create policy "Weine des Abends pflegen" on public.tasting_wines for all to authenticated
  using (exists (select 1 from public.tastings t where t.id = tasting_id and t.host = auth.uid()))
  with check (exists (select 1 from public.tastings t where t.id = tasting_id and t.host = auth.uid()));

grant select, insert, update, delete on public.tastings, public.tasting_wines to authenticated;

-- ---------------------------------------------------------------------
-- 3. Bewertungen: Sichtbarkeit und Zuordnung zum Weinabend
--    Bestehende Bewertungen werden sichtbar (Standard = true).
-- ---------------------------------------------------------------------
alter table public.ratings add column if not exists shared boolean not null default true;
alter table public.ratings add column if not exists tasting_id bigint references public.tastings (id) on delete set null;
create index if not exists ratings_tasting on public.ratings (tasting_id);

-- Freunde sehen geteilte Bewertungen; Noten eines laufenden Weinabends erst nach der Auflösung
drop policy if exists "Bewertungen der Gruppen" on public.ratings;
create policy "Bewertungen der Gruppen" on public.ratings for select to authenticated
  using (shared
         and user_id in (select public.my_friend_ids())
         and (tasting_id is null or not public.tasting_is_open(tasting_id)));

-- Fortschritt eines Weinabends: wie viele Weine jedes Mitglied bewertet hat (ohne Noten)
create or replace function public.tasting_progress(p_tasting bigint)
returns table (user_id uuid, display_name text, rated int)
language sql stable security definer set search_path = ''
as $$
  select gm.user_id, p.display_name,
         (select count(distinct r.wine_id)::int from public.ratings r
           where r.tasting_id = p_tasting and r.user_id = gm.user_id)
  from public.tastings t
  join public.group_members gm on gm.group_id = t.group_id
  join public.profiles p on p.id = gm.user_id
  where t.id = p_tasting
    and t.group_id in (select public.my_group_ids())
  order by p.display_name
$$;

-- Community-Werte beziehen sich ab jetzt auf dich und deine Gruppen
create or replace function public.wine_community(p_wine bigint)
returns table (is_total boolean, vintage smallint, avg_score numeric, n bigint, raters bigint,
               avg_body numeric, avg_acidity numeric, avg_tannin numeric)
language sql stable security definer set search_path = ''
as $$
  select grouping(r.vintage) = 1, r.vintage, avg(r.score), count(*), count(distinct r.user_id),
         avg(r.body), avg(r.acidity), avg(r.tannin)
  from public.ratings r
  where r.wine_id = p_wine and auth.uid() is not null
    and (r.user_id = auth.uid()
         or (r.shared and r.user_id in (select public.my_friend_ids())
             and (r.tasting_id is null or not public.tasting_is_open(r.tasting_id))))
  group by grouping sets ((), (r.vintage))
$$;

create or replace function public.grape_community()
returns table (grape_id bigint, avg_score numeric, n bigint)
language sql stable security definer set search_path = ''
as $$
  select wg.grape_id, avg(r.score), count(*)
  from public.ratings r
  join public.wine_grapes wg on wg.wine_id = r.wine_id and wg.position = 1
  where auth.uid() is not null
    and (r.user_id = auth.uid()
         or (r.shared and r.user_id in (select public.my_friend_ids())
             and (r.tasting_id is null or not public.tasting_is_open(r.tasting_id))))
  group by wg.grape_id
$$;

-- ---------------------------------------------------------------------
-- 4. Empfehlungen an Freunde
-- ---------------------------------------------------------------------
create table if not exists public.recommendations (
  id bigint generated by default as identity primary key,
  from_user uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  to_user uuid not null references public.profiles (id) on delete cascade,
  wine_id bigint not null references public.wines (id) on delete cascade,
  message text check (message is null or length(message) <= 500),
  seen boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists recommendations_to on public.recommendations (to_user, created_at desc);

alter table public.recommendations enable row level security;
drop policy if exists "Empfehlungen lesen" on public.recommendations;
create policy "Empfehlungen lesen" on public.recommendations for select to authenticated
  using (from_user = auth.uid() or to_user = auth.uid());
drop policy if exists "Empfehlung senden" on public.recommendations;
create policy "Empfehlung senden" on public.recommendations for insert to authenticated
  with check (from_user = auth.uid() and to_user in (select public.my_friend_ids()));
drop policy if exists "Empfehlung als gelesen markieren" on public.recommendations;
create policy "Empfehlung als gelesen markieren" on public.recommendations for update to authenticated
  using (to_user = auth.uid()) with check (to_user = auth.uid());
drop policy if exists "Empfehlung löschen" on public.recommendations;
create policy "Empfehlung löschen" on public.recommendations for delete to authenticated
  using (to_user = auth.uid() or from_user = auth.uid());

grant select, insert, update, delete on public.recommendations to authenticated;
grant execute on function public.create_group(text), public.join_group(text), public.tasting_progress(bigint),
  public.my_group_ids(), public.my_friend_ids(), public.is_group_admin(bigint), public.tasting_is_open(bigint) to authenticated;
